#!/usr/bin/env node
// Regenerates src/components/profileAvatarArt.generated.ts from the shared preset art
// (clients/shared/profile-avatars/presets.json), so Fire TV draws exactly the artwork the web client does.
//   node scripts/gen-avatar-art.mjs           write the file
//   node scripts/gen-avatar-art.mjs --check   fail when the file is stale
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../../shared/profile-avatars/presets.json');
const target = path.resolve(here, '../src/components/profileAvatarArt.generated.ts');

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

export function generate(spec) {
  const entries = spec.presets.map((preset) => {
    const elements = preset.art.map((markup) => {
      const [, tag, attrs] = markup.match(/^<(\w+)\s(.*?)\/>$/s);
      const props = Object.fromEntries(
        [...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, key, value]) => [
          camel(key),
          /^-?\d+(\.\d+)?$/.test(value) ? Number(value) : value,
        ]),
      );
      return `    {tag: '${tag}', props: ${JSON.stringify(props).replace(/"([A-Za-z]+)":/g, '$1:').replace(/"/g, "'")}},`;
    });
    return `  ${preset.id}: [\n${elements.join('\n')}\n  ],`;
  });
  return `// Generated by scripts/gen-avatar-art.mjs from clients/shared/profile-avatars/presets.json. Do not edit by hand.
export type AvatarArtElement = {tag: 'circle' | 'path' | 'rect'; props: Record<string, string | number>};

export const PROFILE_AVATAR_ART: Record<string, readonly AvatarArtElement[]> = {
${entries.join('\n')}
};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = generate(JSON.parse(fs.readFileSync(source, 'utf8')));
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) {
      console.error('profileAvatarArt.generated.ts is stale: run node scripts/gen-avatar-art.mjs');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(target, out);
  }
}
